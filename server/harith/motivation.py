def today() -> str:
    """رسالة اليوم — ثابتة للجميع في اليوم نفسه، وتتبدل تلقائيًا كل يوم."""
    return MESSAGES[date.today().toordinal() % len(MESSAGES)]


def ensure_today(app, uid: int, tz: str) -> None:
    """يضمن وجود إشعار اليوم (08:00 محلي) والغد دون تكرار."""
    loc = local_now(tz)
    day = loc.strftime("%Y-%m-%d")
    at = parse_local(f"{day}T08:00", tz)
    if at <= utcnow():
        loc = loc + timedelta(days=1)
        day = loc.strftime("%Y-%m-%d")
        at = parse_local(f"{day}T08:00", tz)
    app.scheduler.enqueue(uid, "motivation", {"day": day}, at,
                          dedupe_key=f"motivation:{uid}:{day}", max_attempts=3)


def cancel_all(app, uid: int) -> None:
    app.db.execute("DELETE FROM jobs WHERE user_id=? AND status='pending' AND kind='motivation'", (uid,))


async def motivation(job: dict, p: dict, app) -> str:
    """يرسل رسالة اليوم إشعارًا هادئًا ثم يجدول نفسه للغد."""
    u = app.db.one("SELECT id, timezone FROM users WHERE id=? AND disabled=0", (job["user_id"],))
    if not u:
        return "مستخدم غير موجود"
    if not app.db.get_setting(u["id"], "motivation_notify", False):
        return "تخطّي: إشعار الرسائل موقوف"
    # إعادة الجدولة للغد أولاً — استمرارية السلسلة حتى لو تعثر الإرسال
    loc = local_now(u["timezone"])
    tomorrow = (loc + timedelta(days=1)).strftime("%Y-%m-%d")
    app.scheduler.enqueue(u["id"], "motivation", {"day": tomorrow},
                          parse_local(f"{tomorrow}T08:00", u["timezone"]),
                          dedupe_key=f"motivation:{u['id']}:{tomorrow}", max_attempts=3)
    if (utcnow() - parse_iso(job["run_at"])).total_seconds() > 3 * 3600:
        return "تخطّي: فات وقت صباح اليوم"
    r = await app.notify(u["id"], f"✨ رسالة اليوم: {today()}", dedupe=f"job:{job['id']}",
                         kind="motivation", push_data={"t": "sync"})
    if r.get("failed") and not any(v is True or v == "queued" for k, v in r.items() if k != "inbox"):
        from .scheduler import RetryLater
        raise RetryLater(r["failed"])
    return "أُرسلت رسالة اليوم"
